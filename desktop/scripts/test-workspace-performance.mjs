import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { chromium } from "@playwright/test";

const root = fileURLToPath(new URL("../", import.meta.url));
const server = await createServer({ root, configFile: `${root}vite.config.ts`, server: { host: "127.0.0.1", port: 0, strictPort: false } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH ?? (existsSync("/usr/bin/chromium") ? "/usr/bin/chromium" : undefined), headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.clock.install();
  await page.goto(`${server.resolvedUrls.local[0]}tests/workspace-performance.html`);
  const get = () => page.evaluate(() => ({ ...window.workspaceTest.counters }));
  const tab = async value => { await page.evaluate(value => window.workspaceTest.tab(value), value); await page.clock.runFor(50); };
  await page.waitForFunction(() => window.workspaceTest?.counters.created === 1);
  await page.clock.runFor(100);
  const first = await get();
  for (let i = 0; i < 20; i++) { await tab("code"); await tab("editor"); }
  assert.equal((await get()).created, first.created, "warm switches must reuse the native view");
  assert.equal((await get()).starts, 1, "warm switches must reuse code-server");
  const stationary = (await get()).bounds;
  await page.clock.runFor(2000);
  assert.equal((await get()).bounds, stationary, "stationary views must not repeat native layout");
  await page.evaluate(() => window.workspaceTest.dirty(true));
  await tab("code"); await page.clock.runFor(45050);
  assert.equal((await get()).stops, 0, "dirty editor must remain alive");
  assert.equal((await get()).closed, 0, "dirty webview must remain alive");
  await tab("editor");
  await page.evaluate(() => window.workspaceTest.dirty(false));
  await tab("code"); await page.clock.runFor(45050);
  assert.equal((await get()).stops, 1, "clean idle editor must stop");
  assert.equal((await get()).closed, 1, "clean idle view must close");
  await tab("editor");
  assert.equal((await get()).starts, 2, "expired editor must restart cleanly");
  await tab("browser");
  await page.getByRole("textbox", { name: "Browser URL" }).fill("http://example.com/start");
  await page.getByRole("button", { name: "Go", exact: true }).click();
  await page.clock.runFor(100);
  const publicViewCount = (await get()).created;
  await page.getByRole("textbox", { name: "Browser URL" }).fill("example.org");
  await page.getByRole("button", { name: "Go", exact: true }).click();
  await page.clock.runFor(100);
  assert.equal(await page.getByRole("textbox", { name: "Browser URL" }).inputValue(), "https://example.org/");
  assert.equal((await get()).created, publicViewCount, "address navigation must preserve the native view and history");
  await page.getByRole("textbox", { name: "Browser URL" }).fill("tauri webview");
  await page.getByRole("button", { name: "Go", exact: true }).click();
  await page.clock.runFor(100);
  assert.equal(await page.getByRole("textbox", { name: "Browser URL" }).inputValue(), "https://duckduckgo.com/?q=tauri%20webview");
  await page.evaluate(() => window.workspaceTest.nativeUrl("http://example.com/after-navigation"));
  await page.clock.runFor(50);
  assert.equal(await page.getByRole("textbox", { name: "Browser URL" }).inputValue(), "http://example.com/after-navigation");
  assert.ok(await page.getByRole("status").filter({ hasText: "Public website" }).count());
  await tab("code"); await page.clock.runFor(45050);
  await tab("browser");
  assert.equal(await page.getByRole("textbox", { name: "Browser URL" }).inputValue(), "http://example.com/after-navigation");
  const before = await get();
  await page.evaluate(() => window.workspaceTest.visibility(false));
  await page.clock.runFor(90000);
  const after = await get();
  for (const key of ["sessionReads", "gitReads", "storageReads", "limitsReads", "probes"]) assert.equal(after[key], before[key], `hidden window must pause ${key}`);
  await page.evaluate(() => window.workspaceTest.visibility(true));
  await tab("editor");
  const background = await get();
  await page.clock.runFor(31000);
  const quiet = await get();
  assert.equal(quiet.gitReads, background.gitReads);
  assert.equal(quiet.storageReads, background.storageReads);
  assert.equal(quiet.sessionReads - background.sessionReads, 2, "background session interval must be 15s");
  for (const size of [{width:1900,height:1000}, {width:900,height:600}]) {
    await page.setViewportSize(size); await page.clock.runFor(100);
    const rect = await page.locator('.cg-workbench[data-mode="editor"]').boundingBox();
    assert.ok(Math.abs(rect.y - 72) < 3 && Math.abs(rect.height - (size.height - 72)) < 3, "editor must fill the content area");
  }
  await tab("code"); await page.clock.runFor(45050);
  const cancelled = await get();
  await page.evaluate(() => window.workspaceTest.deferStart());
  await tab("editor"); await tab("code");
  await page.evaluate(() => window.workspaceTest.releaseStart());
  await page.clock.runFor(45100);
  assert.equal((await get()).created, cancelled.created, "a cancelled cold start must not mount a view");
  assert.equal((await get()).stops, cancelled.stops + 1, "a cancelled cold start must still be cleaned up");
  assert.equal((await get()).probes, 0, "general browsing must not scan local servers");
  console.log(JSON.stringify({ result: "passed", warmSwitches: 20, additionalProcessesForWarmSwitches: 0, additionalViewsForWarmSwitches: 0, stationaryLayoutCalls: 0, finalCounters: await get(), nativeRenderingMeasured: false }, null, 2));
} finally { await browser?.close(); await server.close(); }
