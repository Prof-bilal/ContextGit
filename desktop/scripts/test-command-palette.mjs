import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { chromium } from "@playwright/test";

const root = fileURLToPath(new URL("../", import.meta.url));
const server = await createServer({ root, server: { host: "127.0.0.1", port: 0, strictPort: false } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath: existsSync("/usr/bin/chromium") ? "/usr/bin/chromium" : undefined, headless: true });
  const page = await browser.newPage({ viewport: { width: 1100, height: 800 } });
  await page.route("**/api/**", route => route.fulfill({ json: [] }));
  await page.goto(server.resolvedUrls.local[0]);
  const toggle = page.getByRole("button", { name: "Open command palette" });
  const dialog = page.getByRole("dialog", { name: "Command palette" });
  await toggle.click();
  await dialog.waitFor();
  const search = page.getByRole("combobox", { name: "Search commands" });
  assert.equal(await search.evaluate(element => element === document.activeElement), true);
  await search.fill("Switch to Git");
  assert.equal(await page.getByRole("option").count(), 1);
  await search.press("Enter");
  await dialog.waitFor({ state: "detached" });
  assert.equal(await page.getByRole("tablist", { name: "Workspace views" }).getByRole("tab", { name: "Git", exact: true }).getAttribute("aria-selected"), "true");
  await page.keyboard.press("Control+k");
  await dialog.waitFor();
  await search.fill("switch to");
  await search.press("End");
  assert.match(await page.getByRole("option", { selected: true }).innerText(), /light theme/);
  await search.press("ArrowUp");
  assert.match(await page.getByRole("option", { selected: true }).innerText(), /Browser/);
  await search.press("Home");
  assert.match(await page.getByRole("option", { selected: true }).innerText(), /Code/);
  await search.press("ArrowDown");
  assert.match(await page.getByRole("option", { selected: true }).innerText(), /Git/);
  await search.fill("not-a-real-command");
  await page.getByText("No matching commands.", { exact: true }).waitFor();
  await search.press("Enter");
  assert.equal(await dialog.isVisible(), true);
  await search.fill("light theme");
  await search.press("Enter");
  await dialog.waitFor({ state: "detached" });
  assert.equal(await page.locator(".cg-shell").getAttribute("data-cg-theme"), "light");
  await toggle.click();
  await search.fill("new window");
  await search.press("Enter");
  await page.getByRole("alert").filter({ hasText: "New windows require the desktop app." }).waitFor();
  await page.screenshot({ path: "/tmp/contextgit-command-palette.png" });
  await search.press("Escape");
  await dialog.waitFor({ state: "detached" });
  assert.equal(await toggle.evaluate(element => element === document.activeElement), true);
  await page.keyboard.press("Control+k");
  await dialog.waitFor();
  await page.keyboard.press("Control+k");
  await dialog.waitFor({ state: "detached" });
  console.log("Passed: button, Ctrl+K toggle, search, keyboard selection, execution, theme, empty/error states, Escape and focus restoration.");
} finally { await browser?.close(); await server.close(); }
